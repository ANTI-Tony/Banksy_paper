"""Table 5 (selective editing, pre-registered) from ONE evaluation job (align/sel2/ev1, 10-22: user rule, no mixing of
evaluation runs). Same columns as before; paired bootstrap as in the paper (seed 0, 10000 resamples); re-checks the
pre-registered B1 criteria on the re-read (fewer broken clips than B0, false skips <= 2% of skipped clips, readability not
lower than B0 by more than 0.5 points) and writes <out>/tab_selective.tex, <out>/numbers_sel.tex, <out>/sel.json.
Usage: python make_tab_selective.py <ev1_dir> <dev_selective_40.txt> <out_dir>"""
import json, math, sys
from pathlib import Path
import numpy as np

D, OUT = Path(sys.argv[1]), Path(sys.argv[3]); OUT.mkdir(parents=True, exist_ok=True)
DEV = {l.strip() for l in open(sys.argv[2]) if l.strip()}
E = json.load(open(D / "eval_vlm.json"))["per_clip"]; T = json.load(open(D / "temporal.json"))["per_clip"]
M = json.load(open(D / "mat_stats.json"))["per_clip"]; B = json.load(open(D / "bg.json"))["per_clip"]
C = json.load(open(D / "collateral.json"))["per_clip"]; DEC = json.load(open(D / "decisions.json"))
V = ["B0", "B1", "B2", "B3", "B4"]; ALL = sorted(u for u in E["orig"] if all(u in E.get(m, {}) for m in ["steervte"] + V))
ND = [u for u in ALL if u not in DEV]; ok = lambda m, u: E[m][u]["fixed"] >= 0.6; rng = np.random.default_rng(0)


def mean_of(S, m, k, us): v = [S[m][u][k] for u in us if u in S.get(m, {}) and np.isfinite(S[m][u][k])]; return float(np.mean(v)) if v else float("nan")


def paired(S, k, a, b, us):
    d = np.array([S[a][u][k] - S[b][u][k] for u in us if u in S.get(a, {}) and u in S.get(b, {})], float)
    bs = np.array([d[rng.integers(0, len(d), len(d))].mean() for _ in range(10000)])
    return {"mean": float(d.mean()), "lo": float(np.percentile(bs, 2.5)), "hi": float(np.percentile(bs, 97.5)),
            "p": float(max(2 * min((bs <= 0).mean(), (bs >= 0).mean()), 1e-4)), "n": int(len(d))}


def row(m, us):
    r = {"read": 100 * float(np.mean([ok(m, u) for u in us]))}
    r["fixed"] = sum((not ok("orig", u)) and ok(m, u) for u in us); r["broken"] = sum(ok("orig", u) and not ok(m, u) for u in us); r["net"] = r["fixed"] - r["broken"]
    r["mad"] = mean_of(M, m, "mad", us); r["bg"] = mean_of(B, m, "psnr_bg", us); r["flicker"] = mean_of(T, m, "mc_flicker", us)
    if m in C: r["collat"] = mean_of(C, m, "collat", us)
    return r


S = {"all": {m: row(m, ALL) for m in ["steervte"] + V}, "nondev": {m: row(m, ND) for m in V}}
S["collat_vs_B0_nondev"] = {m: paired(C, "collat", m, "B0", ND) for m in V[1:]}
S["collat_vs_B0_all"] = {m: paired(C, "collat", m, "B0", ALL) for m in V[1:]}
skip = [u for u in ALL if (DEC.get(u, {}).get("select", {}).get("B1") or {}).get("noedit")]
fskip = [u for u in skip if not ok("orig", u)]
b0b, b1b = S["all"]["B0"]["broken"], S["all"]["B1"]["broken"]
S["B1_criteria"] = {"skipped": len(skip), "false_skips": len(fskip), "false_skip_limit": math.floor(0.02 * len(skip)),
                    "broken_B0": b0b, "broken_B1": b1b, "read_B0": S["all"]["B0"]["read"], "read_B1": S["all"]["B1"]["read"],
                    "restored": sum(ok("orig", u) and ok("B1", u) and not ok("B0", u) for u in ALL),
                    "lost": sum(ok("orig", u) and ok("B0", u) and not ok("B1", u) for u in ALL)}
c = S["B1_criteria"]; c["pass"] = bool(c["broken_B1"] < c["broken_B0"] and c["false_skips"] <= max(c["false_skip_limit"], 0) and c["read_B1"] >= c["read_B0"] - 0.5)
json.dump(S, open(OUT / "sel.json", "w"), ensure_ascii=False, indent=1)
f1 = lambda x: f"{x:.1f}"; f2 = lambda x: f"{x:.2f}"
lab = {"B0": "B0: \\method w/o preservation gate", "B1": "B1: + preservation gate (= \\method)", "B2": "B2: + glyph-only erasure", "B3": "B3: + carrier-fit check", "B4": "B4: all three"}
verdict = {"B0": "--", "B1": "adopted" if c["pass"] else "not met", "B2": "rejected", "B3": "rejected", "B4": "rejected"}
best = lambda blk, k, s: (max if s > 0 else min)(S[blk][m][k] for m in V)
L = ["% generated by make_tab_selective.py from align/sel2/ev1 (one evaluation job for every row)", "\\begin{table*}[t]", "\\centering",
     "\\caption{\\textbf{Selective, structure-preserving editing} (pre-registered; 526 clips; one front-end pass, in which the 99 two-row clips were re-run after a compositing fix, and one evaluation run for every row: all rows read together, every metric computed over all rows at once). "
     "B0 is \\method without the preservation gate; each component is added to B0 separately and then all three together (B4). Collateral: change outside the old and new glyphs in the text neighbourhood. "
     "The verdict applies the pre-registered criteria; development clips are excluded in the right block. The B1 of this pass and the \\method of \\cref{tab:main} are the same configuration in two independent front-end passes and evaluation runs.}",
     "\\label{tab:selective}", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{@{}lccccccccc|ccc@{}}", "\\toprule",
     " & \\multicolumn{9}{c|}{All 526 clips} & \\multicolumn{3}{c}{486 clips (no development clips)} \\\\",
     " & Read.\\ $\\uparrow$ & Fixed & Broken & Net & Appear.\\ $\\downarrow$ & BG PSNR & Collateral $\\downarrow$ & Flicker & Verdict & Read.\\ $\\uparrow$ & Net & Collateral $\\Delta$ vs.\\ B0 \\\\", "\\midrule"]
for m in V:
    a, n = S["all"][m], S["nondev"][m]
    bf = lambda blk, k, s, v, f: f"\\textbf{{{f(v)}}}" if round(v, 3) == round(best(blk, k, s), 3) else f(v)
    d = "--" if m == "B0" else (lambda x: f"${x['mean']:+.3f}$ [${x['lo']:+.2f}$, ${x['hi']:+.2f}$]")(S["collat_vs_B0_nondev"][m])
    L.append(f"{lab[m]} & {bf('all','read',1,a['read'],f1)} & {a['fixed']} & {bf('all','broken',-1,a['broken'],str)} & {bf('all','net',1,a['net'],str)} & {bf('all','mad',-1,a['mad'],f2)} & {f2(a['bg'])} & {bf('all','collat',-1,a['collat'],f2)} & {f2(a['flicker'])} & {verdict[m]} & {bf('nondev','read',1,n['read'],f1)} & {bf('nondev','net',1,n['net'],str)} & {d} \\\\")
L += ["\\bottomrule", "\\end{tabular}}", "\\end{table*}"]
(OUT / "tab_selective.tex").write_text("\n".join(L) + "\n")
x2a, x2n = S["collat_vs_B0_all"]["B2"], S["collat_vs_B0_nondev"]["B2"]
mac = {"sReadBzero": f1(S["all"]["B0"]["read"]), "sReadBone": f1(S["all"]["B1"]["read"]), "sReadBtwo": f1(S["all"]["B2"]["read"]),
       "sBrokenBzero": str(b0b), "sBrokenBone": str(b1b), "sRestored": str(c["restored"]), "sLost": str(c["lost"]), "sFalseSkips": str(c["false_skips"]), "sSkipped": str(c["skipped"]),
       "sBtwoCost": f1(S["all"]["B0"]["read"] - S["all"]["B2"]["read"]),
       "sBtwoCollatAll": f"{x2a['mean']:+.3f}", "sBtwoCollatAllLo": f"{x2a['lo']:+.2f}", "sBtwoCollatAllHi": f"{x2a['hi']:+.2f}", "sBtwoCollatAllP": f"{x2a['p']:.3f}",
       "sBtwoCollatNDP": f"{x2n['p']:.2f}"}
with open(OUT / "numbers_sel.tex", "w") as fh:
    fh.write("% generated by make_tab_selective.py from align/sel2/ev1; do not edit by hand\n")
    for k, v in mac.items(): fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(json.dumps({m: {k: round(v, 3) for k, v in r.items()} for m, r in S["all"].items()}, indent=0)); print("B1 criteria:", c); print("B2 collateral vs B0 all / nondev:", x2a, x2n)
